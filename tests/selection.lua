local count=0
local function test(name,body)
    local ok,err=pcall(body); assert(ok,name..': '..tostring(err)); count=count+1; print('PASS selection '..name)
end
local fixture=assert(loadfile('tests/fixtures/selection_services.lua'))()
test('selects owned stored horse without modifying horse or purchase state',function()
    local m=fixture(); assert(m.selected().value.revision==0 and not m.selected().value.selected)
    local r=m.select(0); assert(r.ok and r.value.revision==1 and r.value.available and r.value.horse.horseId==m.t.horseId)
    assert(m.stable().selected_horse_id==m.t.horseId and m.db.horses[m.t.horseId].availability=='stored')
    assert(m.r.Get(m.t.operationId,m.t.characterId).value.state=='fulfilled' and m.asset.status=='active')
end)
test('fresh revision same selection and clearing no-op do not advance revision',function()
    local m=fixture(); assert(m.clear(0).value.revision==0); assert(m.select(0).ok)
    assert(m.select(1).value.revision==1); assert(m.clear(1).value.revision==2)
    assert(m.clear(2).value.revision==2 and not m.selected().value.selected)
end)
test('stale selection revision cannot overwrite a newer preference',function()
    local m=fixture(); assert(m.select(0).ok)
    assert(m.clear(0).code=='revision_conflict' and m.select(0).code=='revision_conflict')
    assert(m.stable().selected_horse_id==m.t.horseId and m.stable().revision==1)
end)
test('disabled set preserves inspection and clearing',function()
    local m=fixture(); assert(m.select(0).ok)
    m.env.StablesConfig.horseSelection=false; assert(m.c.Start().ok)
    assert(m.select(1).code=='selection_disabled' and m.selected().value.available)
    assert(m.clear(1).value.revision==2)
end)
test('other character cannot select the known horse or read owner preference',function()
    local m=fixture(); assert(m.select(0).ok)
    m.context.characterId='20000000-0000-4000-8000-000000000099'
    assert(not m.selected().value.selected and m.selected().value.revision==0)
    assert(m.select(0).code=='horse_not_found')
    assert(m.clear(0).value.revision==0 and m.stable().selected_horse_id==m.t.horseId)
end)
test('canonical ownership loss makes preference unavailable without authorizing use',function()
    local m=fixture(); assert(m.select(0).ok)
    m.asset.owner.holderId='20000000-0000-4000-8000-000000000099'
    local r=m.selected(); assert(r.value.selected and not r.value.available and r.value.horse==nil)
    assert(m.select(1).code=='horse_not_found' and m.clear(1).ok)
end)
test('provider failure is not disguised as an empty selection',function()
    local m=fixture(); assert(m.select(0).ok)
    m.S.Assets.ReadHorse=function() return m.S.Err('assets_unavailable','offline') end
    assert(m.selected().code=='assets_unavailable')
    assert(m.clear(1).ok)
end)
test('session change before mutation refuses selection',function()
    local m=fixture(); m.onAssetRead=function() m.current=false end
    assert(m.select(0).code=='session_stale' and m.stable().selected_horse_id==nil)
end)
test('session change after commit hides response and retains same-character recovery',function()
    local m=fixture(); local reads=0
    m.onAssetRead=function() reads=reads+1; if reads==2 then m.current=false end end
    assert(m.select(0).code=='session_stale' and m.stable().selected_horse_id==m.t.horseId)
    m.current=true; m.onAssetRead=nil; assert(m.selected().value.revision==1)
end)
test('unknown selection commit recovers by read without blind revision retry',function()
    local m=fixture(); local transaction=m.env.DB.transaction
    m.env.DB.transaction=function(body)
        return transaction(function(tx)
            local result=body(tx)
            if m.stable().selected_horse_id then m.unknownCommit=true end
            return result
        end)
    end
    assert(m.select(0).code=='database_error' and m.stable().selected_horse_id==m.t.horseId)
    m.env.DB.transaction=transaction; m.unknownCommit=false
    assert(m.selected().value.revision==1 and m.select(0).code=='revision_conflict')
end)
test('CAS failure rolls back preference revision',function()
    local m=fixture(); m.failSelectionCas=true
    assert(m.select(0).code=='revision_conflict' and m.stable().revision==0 and not m.stable().selected_horse_id)
end)
test('module reload preserves selection and revalidates canonical ownership',function()
    local m=fixture(); assert(m.select(0).ok)
    assert(loadfile('server/selection.lua','t',m.env))(); m.c=m.S.Selection; assert(m.c.Start().ok)
    assert(m.selected().value.revision==1 and m.selected().value.horse.assetId==m.asset.assetId)
end)
test('malformed config and identity injection fail closed',function()
    local m=fixture(); m.env.StablesConfig.horseSelection='true'; assert(m.c.Start().code=='config_error')
    assert(m.c.Set({horseId=m.t.horseId,expectedRevision=0,characterId=m.t.characterId},1,m.context).code=='invalid_input')
    assert(m.c.Clear({expectedRevision=-1},1,m.context).code=='invalid_input')
end)
test('Core selection routes enforce exact bounded payloads',function()
    local m=fixture(); local routes={}
    m.S.Core={Call=function(_,name,callback,options) routes[name]=options; return m.S.Ok(true) end}
    assert(m.c.Install().ok)
    local get=routes['stables.horses.selection.get.v1']; local set=routes['stables.horses.selection.set.v1']; local clear=routes['stables.horses.selection.clear.v1']
    assert(get.requireCharacter and set.requireCharacter and clear.requireCharacter and set.maxPayloadBytes==192)
    assert(get.validatePayload({}) and set.validatePayload({horseId=m.t.horseId,expectedRevision=0})
        and clear.validatePayload({expectedRevision=0}) and not set.validatePayload({horseId=m.t.horseId}))
end)
